#!/usr/bin/env python3
"""T8.1b codegen: transcribe the reference's two `contact_system/contact_models/sym/*.inl`
files (the SymEigen.py-generated barrier law and the vertex/half-plane squared distance)
into the luisa numerics layer.

Why a generator (the T5.2 `scripts/gen_fem_cons_a.py` argument, unchanged): the reference's
`sym/*.inl` files are *machine generated* and must be transcribed **verbatim** -- same
temporary names, same statement order, same association order -- changing only the spelling
of each operator, because LC's DSL scalar operators live at global scope and are shadowed
inside this layer (cookbook RULE M1, §7.2).

This script **imports** the T5.2 transcriber (`scripts/gen_fem_cons_a.py`) instead of
re-implementing it -- the §7.17 rule 14 precedent (`gen_fem_cons_b.py`, `gen_abd_cons_a.py`)
-- and only supplies

  * the T8.1b `REF_DIR`/`DST_DIR`,
  * the two region lists,
  * and one T8.1b-specific difference: the reference's *per-function SymEigen provenance
    block* (`Function generated by SymEigen.py ... LaTeX expression: //tex:$$...$$`) is
    re-inserted verbatim after each generated signature, because the batch's brief requires
    the provenance header and the LaTeX comment to survive the transcription (the T5.2/T6.3a
    .inls carry a file-level banner instead).  The block is copied byte-for-byte out of the
    reference file, so it cannot drift.

The tokenizer / parser / emitter / `--selfcheck` machinery is the very same code
(`gen_fem_cons_a`), so the families cannot drift apart.

Usage
-----
    python scripts/gen_contact_models.py            # rewrite the registered regions
    python scripts/gen_contact_models.py --check    # verify the tree is in sync (rc 1 if stale)
    python scripts/gen_contact_models.py --check --selfcheck
        # + prove every generated statement is a faithful re-spelling (tree identity) and,
        #   for scalar statements, value-exact under 200 random inputs.
        #   A statement whose 200-input evaluation leaves the function's domain (e.g. the
        #   barrier's `log((D - xi^2) / (dHat^2 + 2 dHat xi))` with an unconstrained random
        #   `D - xi^2 < 0`) is reported as `skipped` -- its tree identity is still checked;
        #   the *values* are pinned by the [contact_model] test's own oracles instead.
"""
from __future__ import annotations

import math
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[0]
sys.path.insert(0, str(HERE))

import gen_fem_cons_a as g  # the T5.2 transcriber (tokenizer/parser/emitter/selfcheck)

REF_DIR = ROOT / "src/backends/cuda/contact_system/contact_models"
DST_DIR = ROOT / "src/backends/luisa/contact_system/contact_models"

# (target file, reference file, region name, [reference function names])
REGIONS: list[tuple[str, str, str, list[str]]] = [
    ("sym/codim_ipc_contact.inl",
     "sym/codim_ipc_contact.inl",
     "t81b_codim_ipc_contact",
     ["KappaBarrierWithThickness",
      "dKappaBarrierWithThicknessdD",
      "ddKappaBarrierWithThicknessddD",
      "KappaBarrierLog2",
      "dKappaBarrierLog2dD",
      "ddKappaBarrierLog2ddD",
      "KappaBarrierLog2WithThickness",
      "dKappaBarrierLog2WithThicknessdD",
      "ddKappaBarrierLog2WithThicknessddD"]),
    ("sym/vertex_half_plane_distance.inl",
     "sym/vertex_half_plane_distance.inl",
     "t81b_vertex_half_plane_distance",
     ["HalfPlaneD", "dHalfPlaneDdx", "ddHalfPlaneDddx", "TR", "dTRdx"]),
]


class _DomainEscape(Exception):
    """Raised by the guarded math shim when a random input leaves the domain."""


def _guard(fn):
    def wrapped(*a):
        try:
            return fn(*a)
        except (ValueError, ZeroDivisionError, OverflowError):
            raise _DomainEscape() from None
    return wrapped


class _GuardedMath:
    """`math` with the three transcendental helpers the transcriber value-checks."""
    log = staticmethod(_guard(math.log))
    sqrt = staticmethod(_guard(math.sqrt))
    exp = staticmethod(_guard(math.exp))
    atan2 = staticmethod(_guard(math.atan2))


def provenance_block(reference: str, name: str, occurrence: int) -> str:
    """The reference's per-function SymEigen provenance comment, byte-for-byte.

    The block sits *inside* the function body, directly behind its opening brace and in
    front of `/* Sub Exprs */`.  It is extracted from the raw text (not the
    comment-stripped body `gen_fem_cons_a` works on) so that it is copied verbatim: find
    the declaration, skip its balanced parameter list (which contains no comments), take
    the next `{`, then the comment that follows it up to its closing `****/`."""
    pat = re.compile(r"__host__\s+__device__\s+void\s+" + re.escape(name) + r"\s*\(")
    matches = list(pat.finditer(reference))
    if len(matches) < occurrence:
        raise SystemExit(f"{name}#{occurrence} not found in the reference")
    i = matches[occurrence - 1].end()
    depth = 1
    while depth:
        if reference[i] == "(":
            depth += 1
        elif reference[i] == ")":
            depth -= 1
        i += 1
    brace = reference.index("{", i)
    end = reference.index("****/", brace) + len("****/")
    block = reference[brace + 1 : end]
    if "Function generated by SymEigen.py" not in block:
        raise SystemExit(f"{name}: the block behind the opening brace is not the "
                         f"SymEigen provenance")
    return block


def emitted_function(reference: str, name: str, occurrence: int):
    text, containers, n_stmts, n_pure = g.convert_function(reference, name, occurrence)
    comment = provenance_block(reference, name, occurrence)
    i = text.index("{")
    return text[: i + 1] + "\n" + comment + text[i + 1 :], containers, n_stmts, n_pure


def region_text(reference: str, names: list[str], check_self: bool):
    out, report = [], []
    real_math = g.math
    for spec in names:
        name, occurrence = g.split_name_spec(spec)
        text, containers, n_stmts, n_pure = emitted_function(reference, name, occurrence)
        out.append(text)
        report.append(f" {spec}: {n_stmts} statements ({n_pure} scalar)")
        if check_self:
            g.math = _GuardedMath
            try:
                g.verify_function(reference, name, containers, occurrence)
            except _DomainEscape:
                report.append(f"   {spec}: value check skipped (random input left the domain)")
            finally:
                g.math = real_math
    return "\n".join(out), report


def rewrite(target: Path, reference: Path, region: str, names: list[str], check: bool,
            check_self: bool):
    text = target.read_text(encoding="utf-8")
    b, e = g.begin(region), g.end(region)
    if b not in text or e not in text:
        raise SystemExit(f"{target}: missing sentinels for {region}")
    head, rest = text.split(b, 1)
    _, tail = rest.split(e, 1)
    block, report = region_text(reference.read_text(encoding="utf-8"), names, check_self)
    new = b + "\n" + block + "\n" + e
    changed = head + new + tail != text
    if changed and not check:
        target.write_text(head + new + tail, encoding="utf-8", newline="\n")
    return changed, report


def main() -> int:
    check = "--check" in sys.argv
    selfcheck = "--selfcheck" in sys.argv
    changed_any = False
    for target_name, ref_name, region, names in REGIONS:
        target = DST_DIR / target_name
        reference = REF_DIR / ref_name
        changed, report = rewrite(target, reference, region, names, check, selfcheck)
        changed_any |= changed
        print(f"{'STALE' if changed else 'ok '} {target_name} <- {ref_name} "
              f"({len(names)} functions)")
        for line in report:
            print(line)
    if check and changed_any:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
